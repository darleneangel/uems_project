        flex: 2,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(label.toUpperCase(),
                style: const TextStyle(
                    fontSize: 9,
                    fontWeight: FontWeight.bold,
                    color: Colors.blueGrey)),
            const SizedBox(height: 8),
            Container(
              height: 48,
              width: double.infinity,
              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 14),
              decoration: BoxDecoration(
                  color: Colors.white.withOpacity(0.05),
                  borderRadius: BorderRadius.circular(10),
                  border: Border.all(color: Colors.white10)),
              child: Text(value,
                  style: const TextStyle(
                      color: Colors.white70,
                      fontSize: 12,
                      overflow: TextOverflow.ellipsis)),
            ),
          ],
        ),
      );

  Widget _templateActionMenu(Color textColor) {
    return PopupMenuButton<String>(
      tooltip: "Load Templates",
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
        decoration: BoxDecoration(
            color: aViolet.withOpacity(0.1),
            borderRadius: BorderRadius.circular(10),
            border: Border.all(color: aViolet.withOpacity(0.3))),
        child: const Row(
          children: [
            Icon(LucideIcons.copy, size: 16, color: aViolet),
            SizedBox(width: 8),
            Text("TEMPLATES",
                style: TextStyle(
                    color: aViolet, fontSize: 11, fontWeight: FontWeight.bold)),
          ],
        ),
      ),
      onSelected: (val) {
        if (val == "save_current") {
          _showSaveTemplateDialog();
        } else {
          final template = _localTemplates.firstWhere((t) => t['id'] == val);
          _applyTemplate(template);
        }
      },
      itemBuilder: (context) => [
        const PopupMenuItem(
            value: "save_current",
            child: Row(children: [
              Icon(LucideIcons.save, size: 16, color: success),
              SizedBox(width: 8),
              Text("Save Current as Template")
            ])),
        const PopupMenuDivider(),
        if (_localTemplates.isEmpty)
          const PopupMenuItem(
              enabled: false,
              child: Text("No saved templates",
                  style: TextStyle(color: Colors.grey, fontSize: 12))),
        ..._localTemplates
            .map((t) => PopupMenuItem(value: t['id'], child: Text(t['name']))),
      ],
    );
  }

  void _showSaveTemplateDialog() {
    final nameCtrl = TextEditingController();
    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        backgroundColor: surfaceDark,
        title: const Text("Save Load Template",
            style: TextStyle(color: Colors.white)),
        content: TextField(
          controller: nameCtrl,
          autofocus: true,
          style: const TextStyle(color: Colors.white),
          decoration: const InputDecoration(
              hintText: "Enter Template Name (e.g. BSIT-2A Regular)"),
        ),
        actions: [
          TextButton(
              onPressed: () => Navigator.pop(context),
              child: const Text("CANCEL")),
          ElevatedButton(
              onPressed: () {
                _saveAsTemplate(nameCtrl.text);
                Navigator.pop(context);
              },
              child: const Text("SAVE")),
        ],
      ),
    );
  }

  Widget _buildAssignedList(Color textColor) {
    if (_assignedSubjects.isEmpty) {
      return Center(
          child: Text("No subjects added.",
              style: TextStyle(color: textColor.withOpacity(0.2))));
    }
    return Column(
      children: List.generate(_assignedSubjects.length, (i) {
        final s = _assignedSubjects[i];
        return Container(
          margin: const EdgeInsets.only(bottom: 8),
          padding: const EdgeInsets.all(16),
          decoration: BoxDecoration(
              color: Colors.white.withOpacity(0.02),
              borderRadius: BorderRadius.circular(12)),
          child: Row(
            children: [
              const Icon(LucideIcons.bookOpen, size: 16, color: aViolet),
              const SizedBox(width: 16),
              Expanded(
                  child: Text(s['code'],
                      style: const TextStyle(
                          color: aViolet, fontWeight: FontWeight.bold))),
              Expanded(
                  flex: 2,
                  child: Text(s['professor_name'],
                      style: TextStyle(color: textColor, fontSize: 13))),
              Expanded(
                  flex: 2,
                  child: Text("${s['day']} ${s['time']}",
                      style: const TextStyle(
                          color: Colors.blueGrey, fontSize: 12))),
              IconButton(
                  onPressed: () =>
                      setState(() => _assignedSubjects.removeAt(i)),
                  icon: const Icon(LucideIcons.trash2,
                      size: 16, color: Colors.redAccent)),
            ],
          ),
        );
      }),
    );
  }

  Widget _buildReviewModule(Color textColor, Color bgColor) {
    return Container(
      padding: const EdgeInsets.all(40),
      decoration: BoxDecoration(
          color: bgColor, borderRadius: BorderRadius.circular(24)),
      child: Column(
        children: [
          const Icon(LucideIcons.shieldCheck, color: aViolet, size: 48),
          const SizedBox(height: 24),
          const Text("Academic Compliance Audit",
              style: TextStyle(fontWeight: FontWeight.bold, fontSize: 18)),
          const SizedBox(height: 32),
          _auditRow("Faculty Workload Availability Verified", true),
          _auditRow("General Education Resource Check", true),
          _auditRow("Section Block Density Check (Max 50)", true),
          const SizedBox(height: 48),
          SizedBox(
              width: double.infinity,
              height: 65,
              child: ElevatedButton(
                  onPressed: _finalizeStudyLoads,
                  style: ElevatedButton.styleFrom(
                      backgroundColor: success, foregroundColor: Colors.black),
                  child: const Text("APPROVE & TRANSMIT TO ACCOUNTING",
                      style: TextStyle(fontWeight: FontWeight.bold)))),
        ],
      ),
    );
  }

  Widget _buildHandoverSuccess(Color textColor, Color bgColor) {
    return Center(
      child: Column(children: [
        const Icon(LucideIcons.refreshCw, color: success, size: 64),
        const SizedBox(height: 24),
        const Text("Handover Complete",
            style: TextStyle(
                fontSize: 20,
                fontWeight: FontWeight.bold,
                color: Colors.white)),
        const Text("Load data successfully transmitted.",
            style: TextStyle(color: Colors.blueGrey)),
        const SizedBox(height: 40),
        ElevatedButton(
            onPressed: () {
              setState(() {
                _activeStep = 0;
                _assignedSubjects.clear();
                _selectedStudentIds.clear();
                _initChairContext();
              });
            },
            child: const Text("BACK TO QUEUE"))
      ]),
    );
  }

  Widget _buildHeader(Color text) => Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
            Text("Curriculum Review Console",
                style: GoogleFonts.inter(
                    fontSize: 28,
                    fontWeight: FontWeight.w900,
                    color: text,
                    letterSpacing: -1)),
            Text("Oversight: ${_chairDepartmentName ?? 'Academic Unit'}",
                style: const TextStyle(color: Colors.blueGrey))
          ]),
        ],
      );

  Widget _buildSearchBar(Color bg, Color text) => Container(
      padding: const EdgeInsets.symmetric(horizontal: 16),
      decoration: BoxDecoration(
          color: bg,
          borderRadius: BorderRadius.circular(12),
          border: Border.all(color: Colors.white10)),
      child: TextField(
          controller: _searchController,
          onChanged: (v) => setState(() {}),
          decoration: const InputDecoration(
              hintText: "Filter queue...",
              prefixIcon: Icon(LucideIcons.search, size: 18),
              border: InputBorder.none)));

  Widget _buildMapDropdown(String label, String? value,
          List<Map<String, dynamic>> items, Function(String?) onChanged) =>
      Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Text(label.toUpperCase(),
            style: const TextStyle(
                fontSize: 9,
                fontWeight: FontWeight.bold,
                color: Colors.blueGrey)),
        const SizedBox(height: 8),
        Container(
            padding: const EdgeInsets.symmetric(horizontal: 12),
            decoration: BoxDecoration(
                color: Colors.white.withOpacity(0.05),
                borderRadius: BorderRadius.circular(10)),
            child: DropdownButtonHideUnderline(
                child: DropdownButton<String>(
                    value: value,
                    isExpanded: true,
                    dropdownColor: surfaceDark,
                    style: const TextStyle(color: Colors.white, fontSize: 12),
                    items: items
                        .map((i) => DropdownMenuItem(
                            value: i['id'].toString(),
                            child: Text(i['name'] ?? "${i['fn']} ${i['ln']}",
                                overflow: TextOverflow.ellipsis)))
                        .toList(),
                    onChanged: onChanged)))
      ]);

  Widget _buildWorkflowStepper(Color text) {
    final steps = ["Queue", "Loading", "Review", "Handover"];
    return Row(
        children: List.generate(steps.length, (i) {
      bool active = i == _activeStep;
      bool done = i < _activeStep;
      return Expanded(
          child: Row(children: [
        Container(
            width: 28,
            height: 28,
            decoration: BoxDecoration(
                color: done ? success : (active ? aViolet : Colors.white10),
                shape: BoxShape.circle),
            child: Center(
                child: done
                    ? const Icon(LucideIcons.check,
                        size: 14, color: Colors.black)
                    : Text("${i + 1}",
                        style: TextStyle(
                            color: active ? Colors.white : Colors.blueGrey,
                            fontSize: 10,
                            fontWeight: FontWeight.bold)))),
        const SizedBox(width: 8),
        Text(steps[i],
            style: TextStyle(
                color: active ? aViolet : Colors.blueGrey,
                fontSize: 11,
                fontWeight: active ? FontWeight.bold : FontWeight.normal)),
        if (i < 3)
          Expanded(
              child: Container(
                  height: 1,
                  color: Colors.white10,
                  margin: const EdgeInsets.symmetric(horizontal: 12))),
      ]));
    }));
  }

  Widget _buildErrorState(String error, Color text) => Center(
          child: Column(mainAxisAlignment: MainAxisAlignment.center, children: [
        const Icon(LucideIcons.alertCircle, color: Colors.redAccent, size: 48),
        const SizedBox(height: 16),
        Text(error,
            style: TextStyle(color: text, fontWeight: FontWeight.bold),
            textAlign: TextAlign.center),
        const SizedBox(height: 24),
        ElevatedButton(onPressed: _initChairContext, child: const Text("RETRY"))
      ]));

  Widget _auditRow(String l, bool p) => Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: Row(children: [
        Icon(p ? LucideIcons.checkCircle2 : LucideIcons.alertCircle,
            color: p ? success : Colors.orange, size: 18),
        const SizedBox(width: 12),
        Text(l, style: const TextStyle(color: Colors.blueGrey)),
        const Spacer(),
        Text(p ? "PASSED" : "FAILED",
            style: TextStyle(
                color: p ? success : Colors.orange,
                fontSize: 10,
                fontWeight: FontWeight.bold))
      ]));

  Widget _badge(String t, Color c) => Container(
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
      decoration: BoxDecoration(
          color: c.withOpacity(0.1), borderRadius: BorderRadius.circular(8)),
      child: Text(t,
          style:
              TextStyle(color: c, fontSize: 9, fontWeight: FontWeight.bold)));

  Widget _typeBadge(String t, Color c) => Container(
      padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
      decoration: BoxDecoration(
          color: c.withOpacity(0.1), borderRadius: BorderRadius.circular(4)),
      child: Text(t,
          style:
              TextStyle(color: c, fontSize: 8, fontWeight: FontWeight.w900)));

  Widget _buildEmptyState(Color t) => Center(
      child: Padding(
          padding: const EdgeInsets.all(40),
          child: Text("Queue empty.",
              style: TextStyle(color: t.withOpacity(0.1)))));

  void _showToast(String m, Color c) =>
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(
          content: Text(m),
          backgroundColor: c,
          behavior: SnackBarBehavior.floating));
