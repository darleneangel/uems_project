  Widget _buildWorkflowStepper(Color text) {
    final steps = [
      "Student Queue",
      "Load Advising",
      "Academic Review",
      "Handover Complete"
    ];
    return Row(
        children: List.generate(steps.length, (i) {
      bool active = i == _activeStep;
      bool done = i < _activeStep;
      return Expanded(
          child: Row(children: [
        Container(
            width: 32,
            height: 32,
            decoration: BoxDecoration(
                color: done ? success : (active ? aViolet : Colors.white10),
                shape: BoxShape.circle),
            child: Center(
                child: done
                    ? const Icon(Icons.check_rounded,
                        size: 16, color: Colors.black)
                    : Text("${i + 1}",
                        style: TextStyle(
                            color: active ? Colors.white : Colors.blueGrey,
                            fontSize: 12,
                            fontWeight: FontWeight.bold)))),
        const SizedBox(width: 8),
        Text(steps[i],
            style: TextStyle(
                color: active ? aViolet : Colors.blueGrey,
                fontSize: 13,
                fontWeight: active ? FontWeight.bold : FontWeight.normal)),
        if (i < 3)
          Expanded(
              child: Container(
                  height: 1.5,
                  color: Colors.white10,
                  margin: const EdgeInsets.symmetric(horizontal: 12))),
      ]));
    }));
  }

