import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:lucide_icons/lucide_icons.dart';
import '../../services/supabase_service.dart';

class CurriculumReviewPanel extends StatefulWidget {
  final bool isDarkMode;
  final Map<String, dynamic> userData;

  const CurriculumReviewPanel(
      {super.key, required this.isDarkMode, required this.userData});

  @override
  State<CurriculumReviewPanel> createState() => _CurriculumReviewPanelState();
}

class _CurriculumReviewPanelState extends State<CurriculumReviewPanel> {
  final TextEditingController _searchController = TextEditingController();
  final SupabaseService _service = SupabaseService();

  int _activeStep = 0; // 0: Queue, 1: Loading, 2: Review, 3: Finalized
  final Set<String> _selectedStudentIds = {};
  Map<String, dynamic>? _selectedStudent;

  // --- DATABASE DATA ---
  List<Map<String, dynamic>> _facultyList = [];
  List<Map<String, dynamic>> _subjectCatalog = [];

  // --- LOCAL SYSTEM STORAGE (Session-based Templates) ---
  static final List<Map<String, dynamic>> _localTemplates = [];

  String? _chairDepartmentId;
  String? _chairDepartmentName;
  bool _isContextLoading = true;
  String? _errorMessage;

  // --- FORM SELECTIONS ---
  String? _selectedSubjectId;
  String? _autoGeneratedBlock;

  // AUTO-FILL READ ONLY STATE
  String? _autoFilledFacultyId;
  String? _autoFilledFacultyName;
  String? _autoFilledDay;
  String? _autoFilledTime;

  final List<String> _timeSlots = [
    "07:30 AM - 09:00 AM",
    "09:00 AM - 10:30 AM",
    "10:30 AM - 12:00 PM",
    "01:00 PM - 02:30 PM",
    "02:30 PM - 04:00 PM",
    "04:00 PM - 05:30 PM"
  ];

  static const Color aViolet = Color(0xFF8B5CF6);
  static const Color success = Color(0xFF69F0AE);
  static const Color surfaceDark = Color(0xFF1E1B4B);
  static const Color pViolet = Color(0xFF2E1065);

  List<Map<String, dynamic>> _assignedSubjects = [];
  double get _totalUnits => _assignedSubjects.fold(0.0,
      (sum, item) => sum + (double.tryParse(item['units'].toString()) ?? 0.0));

  @override
  void initState() {
    super.initState();
    _initChairContext();
  }

  /// 🛰️ STEP 1: RESOLVE DEPARTMENT CONTEXT
  Future<void> _initChairContext() async {
    if (!mounted) return;
    setState(() {
      _isContextLoading = true;
      _errorMessage = null;
    });

    final String? resolvedIdNum = widget.userData['user_id_number']?.toString();
    if (resolvedIdNum == null) return;

    try {
      final response = await _service.getChairContext(resolvedIdNum);
      if (response != null && response['department_id'] != null) {
        setState(() {
          _chairDepartmentId = response['department_id']?.toString();
          _chairDepartmentName = response['departments']?['name']?.toString() ??
              "Institutional Unit";
        });
        await _loadMasterData();
      }
    } catch (e) {
      if (mounted) setState(() => _errorMessage = "Database Sync Error: $e");
    } finally {
      if (mounted) setState(() => _isContextLoading = false);
    }
  }

  /// 🛰️ STEP 2: LOAD MASTER DATA
  Future<void> _loadMasterData() async {
    if (_chairDepartmentId == null) return;
    try {
      final List<dynamic> catalogResponse =
          await _service.client.from('subjects').select('*');
      final facultyResponse =
          await _service.getFacultyForChair(_chairDepartmentId!);

      if (mounted) {
        setState(() {
          _facultyList = List<Map<String, dynamic>>.from(facultyResponse);
          _subjectCatalog = List<Map<String, dynamic>>.from(catalogResponse);
        });
      }
    } catch (e) {
      debugPrint("Load Master Data Error: $e");
    }
  }

  /// 🛰️ SMART AUTO-FILL: Fetches data from the "Master Schedule" (Faculty Load Panel)
  Future<void> _autoFillFromMasterSchedule(String subjectId) async {
    try {
      final response = await _service.client
          .from('study_loads')
          .select(
              'professor_id, day_schedule, time_start, time_end, profiles!study_loads_professor_id_fkey(fn, ln)')
          .eq('subject_id', subjectId)
          .filter('student_id', 'is', null)
          .limit(1)
          .maybeSingle();

      if (response != null && mounted) {
        setState(() {
          _autoFilledFacultyId = response['professor_id'].toString();
          final prof = response['profiles'];
          _autoFilledFacultyName = prof != null
              ? "${prof['fn']} ${prof['ln']}"
              : "ASSIGNED PROFESSOR";
          _autoFilledDay = response['day_schedule'];
          _autoFilledTime =
              "${response['time_start']} - ${response['time_end']}";
        });
        _showToast(
            "Auto-filled schedule from Faculty Load.", Colors.blueAccent);
      } else {
        setState(() {
          _autoFilledFacultyId = null;
          _autoFilledFacultyName = "UNASSIGNED";
          _autoFilledDay = "N/A";
          _autoFilledTime = "N/A";
        });
        _showToast("No master schedule found. Assign a professor first.",
            Colors.orangeAccent);
      }
    } catch (e) {
      debugPrint("Master Schedule Sync Error: $e");
    }
  }

  /// 💾 LOCAL TEMPLATE ACTIONS
  void _saveAsTemplate(String templateName) {
    if (_assignedSubjects.isEmpty) return;
    setState(() {
      _localTemplates.add({
        'id': DateTime.now().millisecondsSinceEpoch.toString(),
        'name': templateName,
        'subjects_data': List<Map<String, dynamic>>.from(_assignedSubjects),
      });
    });
    _showToast("Template '$templateName' saved locally.", success);
  }

  void _applyTemplate(Map<String, dynamic> template) {
    setState(() {
      final List<dynamic> data = template['subjects_data'];
      _assignedSubjects = List<Map<String, dynamic>>.from(data);
    });
    _showToast("Applied template: ${template['name']}", aViolet);
  }

  /// 📐 LOGIC: Generate Block
  Future<String> _generateDynamicBlock(
      String courseCode, String yearLevel) async {
    final String yearNum = yearLevel.replaceAll(RegExp(r'[^0-9]'), '');
    final String baseBlock = "$courseCode-$yearNum";
    try {
      final List<dynamic> roster = await _service.client
          .from('student_details')
          .select('profile_id')
          .eq('courses!inner(code)', courseCode)
          .eq('year_levels!inner(definition)', yearLevel);
      if (roster.length < 50) return baseBlock;
      int sectionIndex = roster.length ~/ 50;
      return "$baseBlock${String.fromCharCode(65 + sectionIndex)}";
    } catch (e) {
      return baseBlock;
    }
  }

  Future<void> _handleStepTransition(Map<String, dynamic> student) async {
    setState(() => _isContextLoading = true);
    final details = student['student_details'];
    Map<String, dynamic>? studentInfo =
        (details is List && details.isNotEmpty) ? details[0] : details;

    if (studentInfo == null) {
      _showToast("Missing Student Record Details.", Colors.redAccent);
      setState(() => _isContextLoading = false);
      return;
    }

    final String cCode = (studentInfo['courses']?['code'] ?? "GEN").toString();
    final String yLevel =
        (studentInfo['year_levels']?['definition'] ?? "1st Year").toString();
    final block = await _generateDynamicBlock(cCode, yLevel);

    setState(() {
      _selectedStudent = student;
      _autoGeneratedBlock = block;
      _isContextLoading = false;
      _activeStep = 1;
    });
  }

  /// 🛰️ FINALIZATION:
  /// Now updates status to 'Assessment' to alert Accounting
  Future<void> _finalizeStudyLoads() async {
    if (_assignedSubjects.isEmpty) return;
    setState(() => _isContextLoading = true);

    final targetIds = _selectedStudentIds.isNotEmpty
        ? _selectedStudentIds.toList()
        : [_selectedStudent!['id']];

    try {
      List<Map<String, dynamic>> studyLoads = [];
      for (String sId in targetIds) {
        for (var sub in _assignedSubjects) {
          studyLoads.add({
            'student_id': sId,
            'subject_id': sub['id'],
            'professor_id': sub['professor_id'],
            'section_block': sub['block'],
            'day_schedule': sub['day'],
            'time_start': sub['time'].split(' - ')[0],
            'time_end': sub['time'].split(' - ')[1],
          });
        }
      }

      // 1. Assign the subjects
      await _service.batchAssignSubjects(studyLoads);

      // 2. Transmit to Accounting (Update Status)
      // FIX: Changed "Pending Assessment" to "Assessment" to resolve DB check constraint violation
      for (String sId in targetIds) {
        await _service.client
            .from('student_details')
            .update({'enrollment_status': 'Assessment'}).eq('profile_id', sId);
      }

      if (mounted) {
        setState(() {
          _activeStep = 3;
          _selectedStudentIds.clear();
          _assignedSubjects = [];
          _isContextLoading = false;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isContextLoading = false);
        _showToast("Sync Error: $e", Colors.redAccent);
      }
    }
  }

  void _addSubjectToSession() {
    if (_selectedSubjectId == null || _autoFilledFacultyId == null) return;

    final subject = _subjectCatalog
        .firstWhere((s) => s['id'].toString() == _selectedSubjectId);

    setState(() {
      _assignedSubjects.add({
        "id": subject['id'],
        "code": subject['code'],
        "title": subject['name'],
        "units": subject['units'],
        "professor_id": _autoFilledFacultyId,
        "professor_name": _autoFilledFacultyName,
        "block": _autoGeneratedBlock,
        "day": _autoFilledDay,
        "time": _autoFilledTime,
      });
      _selectedSubjectId = null;
      _autoFilledFacultyId = null;
      _autoFilledFacultyName = null;
      _autoFilledDay = null;
      _autoFilledTime = null;
    });
  }

  @override
  Widget build(BuildContext context) {
    final textColor = widget.isDarkMode ? Colors.white : pViolet;
    final bgColor = widget.isDarkMode ? surfaceDark : Colors.white;

    if (_isContextLoading) {
      return const Center(child: CircularProgressIndicator(color: aViolet));
    }
    if (_errorMessage != null) {
      return _buildErrorState(_errorMessage!, textColor);
    }

    return SingleChildScrollView(
      physics: const BouncingScrollPhysics(),
      padding: const EdgeInsets.all(40),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          _buildHeader(textColor),
          const SizedBox(height: 32),
          _buildWorkflowStepper(textColor),
          const SizedBox(height: 32),
          _buildActiveModuleContent(textColor, bgColor),
        ],
      ),
    );
  }

  Widget _buildActiveModuleContent(Color textColor, Color bgColor) {
    switch (_activeStep) {
      case 0:
        return _buildStudentQueue(textColor, bgColor);
      case 1:
        return _buildSubjectLoadingInterface(textColor, bgColor);
      case 2:
        return _buildReviewModule(textColor, bgColor);
      case 3:
        return _buildHandoverSuccess(textColor, bgColor);
      default:
        return _buildStudentQueue(textColor, bgColor);
    }
  }

  Widget _buildStudentQueue(Color textColor, Color bgColor) {
    if (_chairDepartmentId == null) return _buildEmptyState(textColor);
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Expanded(child: _buildSearchBar(bgColor, textColor)),
            if (_selectedStudentIds.isNotEmpty) ...[
              const SizedBox(width: 16),
              ElevatedButton.icon(
                onPressed: () => setState(() => _activeStep = 1),
                icon: const Icon(LucideIcons.users),
                label: Text(
                    "BATCH ASSIGN (${_selectedStudentIds.length} STUDENTS)"),
                style: ElevatedButton.styleFrom(
                    backgroundColor: aViolet,
                    padding: const EdgeInsets.all(22)),
              ),
            ]
          ],
        ),
        const SizedBox(height: 24),
        FutureBuilder<List<Map<String, dynamic>>>(
          future: _service.getStudentQueue(_chairDepartmentId!),
          builder: (context, snapshot) {
            if (!snapshot.hasData) {
              return const Center(
                  child: CircularProgressIndicator(color: aViolet));
            }
            final list = snapshot.data!.where((s) {
              return s['fn']
                  .toString()
                  .toLowerCase()
                  .contains(_searchController.text.toLowerCase());
            }).toList();
            if (list.isEmpty) return _buildEmptyState(textColor);

            return ListView.builder(
              shrinkWrap: true,
              physics: const NeverScrollableScrollPhysics(),
              itemCount: list.length,
              itemBuilder: (context, i) {
                final s = list[i];
                bool isSelected = _selectedStudentIds.contains(s['id']);
                final details = s['student_details'];
                Map<String, dynamic>? info =
                    (details is List && details.isNotEmpty)
                        ? details[0]
                        : details;
                bool isIrreg = info?['student_type'] == 'Irregular';

                return Container(
                  margin: const EdgeInsets.only(bottom: 12),
                  padding: const EdgeInsets.all(20),
                  decoration: BoxDecoration(
                      color: bgColor,
                      borderRadius: BorderRadius.circular(16),
                      border: Border.all(
                          color: isSelected ? aViolet : Colors.white10)),
                  child: Row(
                    children: [
                      Checkbox(
                          value: isSelected,
                          activeColor: aViolet,
                          onChanged: (v) => setState(() => v!
                              ? _selectedStudentIds.add(s['id'])
                              : _selectedStudentIds.remove(s['id']))),
                      const SizedBox(width: 12),
                      Expanded(
                          child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                            Row(children: [
                              Text("${s['fn']} ${s['ln']}",
                                  style: TextStyle(
                                      color: textColor,
                                      fontWeight: FontWeight.bold)),
                              const SizedBox(width: 8),
                              _typeBadge(isIrreg ? 'IRREGULAR' : 'REGULAR',
                                  isIrreg ? Colors.orange : success),
                            ]),
                            Text(
                                "${s['user_id_number']} • ${info?['courses']?['code'] ?? 'N/A'} • ${info?['year_levels']?['definition'] ?? 'N/A'}",
                                style: const TextStyle(
                                    color: Colors.blueGrey, fontSize: 12))
                          ])),
                      ElevatedButton(
                          onPressed: () => _handleStepTransition(s),
                          child: const Text("Assign Subjects")),
                    ],
                  ),
                );
              },
            );
          },
        ),
      ],
    );
  }

  Widget _buildSubjectLoadingInterface(Color textColor, Color bgColor) {
    return Container(
      padding: const EdgeInsets.all(32),
      decoration: BoxDecoration(
          color: bgColor,
          borderRadius: BorderRadius.circular(24),
          border: Border.all(color: Colors.white10)),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text("Study Load Configuration",
                    style: GoogleFonts.inter(
                        fontWeight: FontWeight.bold,
                        color: textColor,
                        fontSize: 18)),
                Text("TARGET BLOCK: ${_autoGeneratedBlock ?? 'N/A'}",
                    style: const TextStyle(
                        color: aViolet,
                        fontWeight: FontWeight.bold,
                        fontSize: 12)),
              ]),
              Row(
                children: [
                  _templateActionMenu(textColor),
                  const SizedBox(width: 12),
                  _badge("DEPT: $_chairDepartmentName", aViolet),
                ],
              ),
            ],
          ),
          const Divider(height: 48, color: Colors.white10),
          Row(
            crossAxisAlignment: CrossAxisAlignment.end,
            children: [
              Expanded(
                  flex: 3,
                  child: _buildMapDropdown("Institutional Catalog",
                      _selectedSubjectId, _subjectCatalog, (v) {
                    setState(() => _selectedSubjectId = v);
                    if (v != null) _autoFillFromMasterSchedule(v);
                  })),
              const SizedBox(width: 12),
              _readOnlyField("Professor (Master)",
                  _autoFilledFacultyName ?? "Select Subject"),
              const SizedBox(width: 12),
              _readOnlyField("Schedule",
                  "${_autoFilledDay ?? ''} ${_autoFilledTime ?? ''}"),
              const SizedBox(width: 16),
              IconButton(
                  onPressed: _addSubjectToSession,
                  icon: const Icon(LucideIcons.plusCircle,
                      color: success, size: 36)),
            ],
          ),
          const SizedBox(height: 40),
          _buildAssignedList(textColor),
          const SizedBox(height: 32),
          Row(mainAxisAlignment: MainAxisAlignment.end, children: [
            Text("Total Units: $_totalUnits",
                style: GoogleFonts.orbitron(
                    color: textColor,
                    fontWeight: FontWeight.bold,
                    fontSize: 18)),
            const SizedBox(width: 24),
            ElevatedButton(
                onPressed: _assignedSubjects.isEmpty
                    ? null
                    : () => setState(() => _activeStep = 2),
                child: const Text("VALIDATE & REVIEW")),
          ]),
        ],
      ),
    );
  }

