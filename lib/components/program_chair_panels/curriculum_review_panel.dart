  void _showManageCatalogDialog(BuildContext context) {
    final codeCtrl = TextEditingController();
    final nameCtrl = TextEditingController();
    final unitsCtrl = TextEditingController();

    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        backgroundColor: surfaceDark,
        title: const Text("Update Institutional Catalog",
            style: TextStyle(color: Colors.white, fontWeight: FontWeight.bold)),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            TextField(
                controller: codeCtrl,
                decoration: const InputDecoration(hintText: "Code"),
                style: const TextStyle(color: Colors.white)),
            TextField(
                controller: nameCtrl,
                decoration: const InputDecoration(hintText: "Title"),
                style: const TextStyle(color: Colors.white)),
            TextField(
                controller: unitsCtrl,
                decoration: const InputDecoration(hintText: "Units"),
                style: const TextStyle(color: Colors.white),
                keyboardType: TextInputType.number),
          ],
        ),
        actions: [
          TextButton(
              onPressed: () => Navigator.pop(context),
              child: const Text("CANCEL")),
          ElevatedButton(
              onPressed: () async {
                try {
                  await _service.addSubjectToCatalog({
                    'code': codeCtrl.text.toUpperCase(),
                    'name': nameCtrl.text,
                    'units': int.tryParse(unitsCtrl.text) ?? 3,
                    'department_id': _chairDepartmentId,
                  });
                  await _loadMasterData();
                  Navigator.pop(context);
                } catch (e) {
                  _showToast("Subject insertion failed.", Colors.redAccent);
                }
              },
              child: const Text("SAVE")),
        ],
      ),
    );
  }

  void _showToast(String m, Color c) =>
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(
          content: Text(m),
          backgroundColor: c,
          behavior: SnackBarBehavior.floating));

  Future<void> _generateSyncReport(int count) async {
    final pdf = pw.Document();
    pdf.addPage(pw.Page(
        build: (c) => pw.Center(
            child:
                pw.Text("Study Load Handover Logged for $count students."))));
    final dir = await getTemporaryDirectory();
    final file =
        File("${dir.path}/Sync_${DateTime.now().millisecondsSinceEpoch}.pdf");
    await file.writeAsBytes(await pdf.save());
  }
