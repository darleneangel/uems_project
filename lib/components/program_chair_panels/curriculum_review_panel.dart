  Widget _buildFormDropdown(String label, String currentVal,
      List<String> options, ValueChanged<String?> onChanged, double width) {
    final dropBg = widget.isDarkMode
        ? Colors.white.withOpacity(0.04)
        : Colors.grey.shade200;
    final dropBorder = widget.isDarkMode ? Colors.white10 : Colors.black12;

    // Safety: ensure currentVal is one of the options to prevent DropdownButton assertion crashes
    final List<String> safeOptions = List.from(options);
    if (!safeOptions.contains(currentVal)) {
      safeOptions.add(currentVal);
    }

    return SizedBox(
      width: width,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(label.toUpperCase(),
              style: const TextStyle(
                  color: Colors.blueGrey,
                  fontSize: 10,
                  fontWeight: FontWeight.bold,
                  letterSpacing: 1)),
          const SizedBox(height: 8),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 14),
            height: 52,
            decoration: BoxDecoration(
              color: dropBg,
              borderRadius: BorderRadius.circular(12),
              border: Border.all(color: dropBorder),
            ),
            child: DropdownButtonHideUnderline(
              child: DropdownButton<String>(
                value: currentVal,
                isExpanded: true,
                dropdownColor:
                    widget.isDarkMode ? const Color(0xFF1E1B4B) : Colors.white,
                icon: const Icon(Icons.arrow_drop_down_rounded,
                    color: aViolet, size: 28),
                style: TextStyle(
                    color: widget.isDarkMode ? Colors.white : pViolet,
                    fontWeight: FontWeight.bold,
                    fontSize: 13),
                items: safeOptions
                    .map((opt) => DropdownMenuItem(
                          value: opt,
                          child: Text(opt),
                        ))
                    .toList(),
                onChanged: onChanged,
              ),
            ),
          ),
        ],
      ),
    );
  }

  Widget _templateActionMenu(Color textColor) {
    return PopupMenuButton<String>(
      tooltip: "Load Templates",
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 18, vertical: 10),
        decoration: BoxDecoration(
            color: aViolet.withOpacity(0.1),
            borderRadius: BorderRadius.circular(12),
            border: Border.all(color: aViolet.withOpacity(0.3))),
        child: const Row(
          children: [
            Icon(Icons.layers_rounded, size: 18, color: aViolet),
            const SizedBox(width: 8),
            Text("TEMPLATES",
                style: TextStyle(
                    color: aViolet,
                    fontSize: 12,
                    fontWeight: FontWeight.bold,
                    letterSpacing: 0.5)),
          ],
        ),
      ),
      onSelected: (val) {
        if (val == "save_current") {
          _showSaveTemplateDialog();
        } else {
          final template = _localTemplates.firstWhere((t) => t['id'] == val);
          _applyTemplate(template);
        }
      },
      itemBuilder: (context) => [
