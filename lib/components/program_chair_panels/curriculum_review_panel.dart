  }

  Widget _buildHandoverSuccess(Color textColor, Color bgColor) {
    return Center(
      child: Column(children: [
        const Icon(LucideIcons.refreshCw, color: success, size: 64),
        const SizedBox(height: 24),
        Text("Handover Complete",
            style: GoogleFonts.inter(
                fontSize: 20, fontWeight: FontWeight.bold, color: textColor)),
        const Text(
            "Load data successfully transmitted. Student can now see their schedule.",
            style: TextStyle(color: Colors.blueGrey)),
        const SizedBox(height: 40),
        ElevatedButton(
            onPressed: () => setState(() {
                  _activeStep = 0;
                  _assignedSubjects.clear();
                  _selectedStudentIds.clear();
                  _initChairContext();
                }),
            child: const Text("BACK TO QUEUE"))
      ]),
    );
  }

